def _split(items):
    """แยกหัวข้อ (h3 ตัวแรก) ออกจากเนื้อหา"""
    title, rest = None, []
    for x in items:
        m = re.search(r"<h3>(.*?)</h3>", x)
        if m and title is None:
            title = m.group(1)
            x = x.replace(m.group(0), "", 1)
            if x.strip():
                rest.append(x)
        else:
            rest.append(x)
    return title, rest


